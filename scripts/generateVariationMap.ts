// scripts/generateVariationMap.ts
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { SKILL_BUCKETS } from '../src/constants/skillBuckets.js';
import { TopicMap } from '../api/question.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const OUTPUT_PATH = path.resolve(__dirname, '../src/constants/variationMap.js');

interface VariationSample {
    description: string | null;
    latex: string | null;
    hasVisual: boolean;
    options?: Array<{ id: string; label: string }>;
}

interface VariationEntry {
    topicId: string;
    variationKey: string;
    level: number;
    sv: VariationSample;
    en: VariationSample;
}

function extractMinimalSample(rawQuestion: any): VariationSample {
    const rd = rawQuestion?.renderData || {};
    const hasVisual = Boolean(
        rd.geometry || rd.graph || rd.pattern || rd.marbles || rd.diagram || rd.visualType
    );

    const sample: VariationSample = {
        description: rd.description ? String(rd.description).trim() : null,
        latex: rd.latex ? String(rd.latex).trim() : null,
        hasVisual
    };

    if (Array.isArray(rd.options) && rd.options.length > 0) {
        sample.options = rd.options.map((o: any, idx: number) => ({
            id: o.id || ['A', 'B', 'C', 'D'][idx] || String(idx + 1),
            label: String(o.label ?? o.text ?? '')
        }));
    }

    return sample;
}

async function generateVariationMap() {
    const variationMap: Record<string, VariationEntry> = {};
    let totalGenerated = 0;
    let totalErrors = 0;

    for (const [catId, catData] of Object.entries(SKILL_BUCKETS as Record<string, any>)) {
        if (!catData?.topics) continue;

        for (const [topicId, topicData] of Object.entries(catData.topics as Record<string, any>)) {
            const GeneratorClass = TopicMap[topicId];

            if (!GeneratorClass) {
                console.warn(`⚠️  Skipping topic "${topicId}" (not found in TopicMap)`);
                continue;
            }

            const generator = new GeneratorClass();
            const variations = Array.isArray(topicData.variations) ? topicData.variations : [];

            for (const v of variations) {
                if (!v?.key) continue;
                const mapKey = `${topicId}__${v.key}`;
                const level = Number(v.level || 1);

                try {
                    const rawSv = typeof generator.generateByVariation === 'function'
                        ? generator.generateByVariation(String(v.key), 'sv')
                        : generator.generate(level, 'sv');

                    const rawEn = typeof generator.generateByVariation === 'function'
                        ? generator.generateByVariation(String(v.key), 'en')
                        : generator.generate(level, 'en');

                    if (!rawSv || !rawEn) {
                        throw new Error('Generator returned null/undefined');
                    }

                    variationMap[mapKey] = {
                        topicId,
                        variationKey: v.key,
                        level,
                        sv: extractMinimalSample(rawSv),
                        en: extractMinimalSample(rawEn)
                    };

                    totalGenerated++;
                } catch (err: any) {
                    totalErrors++;
                    console.error(`❌ Error generating ${mapKey} (cat: ${catId}):`, err?.message || err);
                }
            }
        }
    }

    const fileBanner = `// AUTO-GENERATED FILE — DO NOT EDIT MANUALLY
// Generated by: npm run gen:variations
// Total variations: ${totalGenerated}

export const VARIATION_MAP = ${JSON.stringify(variationMap, null, 2)};
`;

    fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
    fs.writeFileSync(OUTPUT_PATH, fileBanner, 'utf-8');

    console.log(`\n✅ Wrote ${totalGenerated} variations to ${OUTPUT_PATH}`);
    if (totalErrors > 0) {
        console.warn(`⚠️  ${totalErrors} variations failed to generate (see logs above).`);
    }
}

generateVariationMap();